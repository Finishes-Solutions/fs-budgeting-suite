#!/usr/bin/env node
// Regenerate the coverage tables in docs/RESEARCH.md from the compiled bundle.
//
//   node tools/research-coverage.js            # rewrite the block between the markers
//   node tools/research-coverage.js --print    # print the tables only
//
// "S" = the default cites sourced evidence; "D" = derived estimate (labelled
// "derived estimate — verify" in the app); "—" = not applicable to the type.
'use strict';
const fs = require('fs');
const path = require('path');
const D = require('../app/research-data.js');

const mark = r => (!r ? '—' : r.source && !r.source.derived && r.source.evidence.length ? 'S' : 'D');
const money = v => '$' + Math.round(v).toLocaleString('en-US');
const { _: { unitLabel } } = require('../app/budget-engine.js');
const unitL = id => unitLabel(D, id);

function typeRows() {
  const cats = D.categories.map(c => c.id);
  return Object.values(D.types).sort((a, b) => cats.indexOf(a.category) - cats.indexOf(b.category) || a.name.localeCompare(b.name)).map(t => {
    const h = t.hardCost.perPrimaryUnit;
    const ev = Object.values(D.evidence).filter(e => e.id.indexOf(t.file + '#') === 0);
    const conf = { high: 0, medium: 0, low: 0 };
    ev.forEach(e => { conf[e.confidence] = (conf[e.confidence] || 0) + 1; });
    const items = t.lineItems.length;
    const itemsS = t.lineItems.filter(li => li.cost && !li.cost.source.derived && li.cost.source.evidence.length).length;
    const overall = !h || h.source.derived ? (ev.length >= 3 ? 'M-L' : 'L') : conf.high >= 2 ? 'H' : conf.high + conf.medium >= 3 ? 'M' : 'M-L';
    return '| ' + [t.name + ' (`' + t.id + '`)', unitL(t.primaryUnit), h ? money(h.mid) : 'blocks', ev.length,
      mark(h), mark(t.hardCost.perSF), mark(t.systemSplit), items ? itemsS + '/' + items : '—', t.ffe ? mark(t.ffe.perPrimaryUnit) : '—',
      mark(t.softCosts.pctOfHard), mark(t.contingency.hard), mark(t.sizing.typicalSize), overall].join(' | ') + ' |';
  });
}

function blockRows() {
  const g = {};
  Object.values(D.blocks).forEach(b => { (g[b.blockName] = g[b.blockName] || []).push(b); });
  return Object.keys(g).sort().map(k => {
    const items = g[k], s = items.filter(b => !b.cost.source.derived && b.cost.source.evidence.length).length;
    const withEv = items.filter(b => b.cost.source.evidence.length).length;
    return '| ' + [k, items.length, s, withEv - s, items.length - withEv].join(' | ') + ' |';
  });
}

function commonRows() {
  return Object.keys(D.common).sort().map(k => {
    const items = Object.values(D.common[k].items);
    const s = items.filter(i => i.range && i.range.source && !i.range.source.derived && i.range.source.evidence.length).length;
    return '| ' + [k, items.length, s, items.length - s].join(' | ') + ' |';
  });
}

function tables() {
  const types = Object.values(D.types);
  const hcS = types.filter(t => t.hardCost.perPrimaryUnit && !t.hardCost.perPrimaryUnit.source.derived).length;
  return [
    '<!-- coverage:start (generated by tools/research-coverage.js — do not edit by hand) -->',
    '',
    `Research bundle \`${D.version}\`: **${types.length} project types**, **${Object.keys(D.blocks).length} building-block items**, `
      + `**${Object.keys(D.evidence).length} sourced evidence items**. Baseline hard cost is sourced for **${hcS} of ${types.length}** types; `
      + `the rest are derived estimates built from cited comparables.`,
    '',
    '### Project types',
    '',
    'S = sourced default · D = derived estimate — verify · — = not applicable. "Items" = sourced / total type-specific line items.',
    '',
    '| Type | Unit | Hard cost mid (national, ' + D.baseYear + ' $) | Evidence | Hard/unit | Hard/SF | CSI split | Items | FF&E | Soft % | Contingency | Sizing | Overall |',
    '|---|---|---:|---:|---|---|---|---|---|---|---|---|---|',
    ...typeRows(),
    '',
    '### Building blocks',
    '',
    '| Block | Items | Sourced | Derived from cited evidence | Derived, no evidence |',
    '|---|---:|---:|---:|---:|',
    ...blockRows(),
    '',
    '### Shared norms and indices',
    '',
    '| File | Items | Sourced | Derived |',
    '|---|---:|---:|---:|',
    ...commonRows(),
    '',
    '<!-- coverage:end -->'
  ].join('\n');
}

function summaries() {
  const out = ['<!-- summaries:start (generated by tools/research-coverage.js — do not edit by hand) -->', ''];
  D.categories.forEach(c => {
    const ts = Object.values(D.types).filter(t => t.category === c.id).sort((a, b) => a.name.localeCompare(b.name));
    if (!ts.length) return;
    out.push('### ' + c.name, '');
    ts.forEach(t => {
      const h = t.hardCost.perPrimaryUnit;
      const rc = t.rangeCheck;
      out.push('**' + t.name + '** (`' + t.id + '`, per ' + unitL(t.primaryUnit) + ') — baseline ' + (h ? money(h.low) + ' / ' + money(h.mid) + ' / ' + money(h.high) : 'assembled from blocks')
        + (h && h.source.derived ? ' *(derived estimate — verify)*' : '') + (rc && rc.max < 1e11 ? '; all-in range check ' + money(rc.min) + '–' + money(rc.max) : '')
        + '. ' + (t.summary || ''), '');
    });
  });
  out.push('<!-- summaries:end -->');
  return out.join('\n');
}

function replaceBlock(cur, start, end, body) {
  const a = cur.indexOf(start), b = cur.indexOf(end);
  if (a < 0 || b < 0) throw new Error('markers not found: ' + start);
  return cur.slice(0, a) + body + cur.slice(b + end.length);
}

if (require.main === module) {
  if (process.argv.includes('--print')) { console.log(tables() + '\n\n' + summaries()); process.exit(0); }
  const p = path.join(__dirname, '..', 'docs', 'RESEARCH.md');
  let cur = fs.readFileSync(p, 'utf8');
  cur = replaceBlock(cur, '<!-- coverage:start', '<!-- coverage:end -->', tables());
  cur = replaceBlock(cur, '<!-- summaries:start', '<!-- summaries:end -->', summaries());
  fs.writeFileSync(p, cur);
  console.log('updated docs/RESEARCH.md coverage tables and type summaries');
}
module.exports = { tables, summaries };
